def build(code, pairs):
    s = (ROOT / "index.html").read_text()
    missing = [en for en, _ in pairs if en not in s]
    if missing:
        sys.exit(f"{code}: English source changed, update i18n.py for:\n  " + "\n  ".join(missing))
    # longest first, so a phrase nested inside a longer one can't pre-empt it
    for en, tr in sorted(pairs, key=lambda p: -len(p[0])):
        s = s.replace(en, tr)
    out = ROOT / code / "index.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(s)
    print(f"wrote {out.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    build("tr", TR)
    build("zh", ZH)
